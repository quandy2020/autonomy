/// Invalid geometry or missing XML may not disturb an accepted invocation.
void InvalidPreservesAccepted()
{
    XmlFile xml; Harness task; Start(task, Goal(xml));
    auto invalid = Goal(xml, "B"); invalid.clear_goals();
    Require(!task.SubmitGoal(invalid), "empty geometry rejected");
    invalid = Goal(xml, "B");
    invalid.mutable_goals(0)->mutable_pose()->mutable_position()->set_x(
        std::numeric_limits<double>::quiet_NaN());
    Require(!task.SubmitGoal(invalid), "nonfinite geometry rejected");
    invalid = Goal(xml, "B"); invalid.mutable_goals(0)->mutable_pose()->clear_orientation();
    Require(!task.SubmitGoal(invalid), "zero quaternion rejected");
    invalid = Goal(xml, "B"); *invalid.add_goals()=invalid.goals(0);
    invalid.mutable_goals(1)->mutable_header()->set_frame_id("other-frame");
    Require(!task.SubmitGoal(invalid), "inconsistent frames rejected");
    invalid = Goal(xml, "B"); invalid.set_mode(static_cast<proto::NavigationMode>(99));
    Require(!task.SubmitGoal(invalid), "unknown mode rejected");
    invalid = Goal(xml, "B"); invalid.mutable_plugins()->set_behavior_tree(xml.path()+".missing");
    Require(!task.SubmitGoal(invalid), "missing XML rejected before cancellation");
    Identity(task, "A", TaskLifecycle::kRunning);
    Require(task.probe->starts == 1 && task.probe->halts == 0,
            "rejected goals preserve actual node execution");
}

