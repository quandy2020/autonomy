/// Fail a contract assertion with a useful native test error.
void Require(bool value, const char* message)
{
    if (!value) throw std::runtime_error(message);
}

/// Wait for observed effects with a bounded deadline, not a guessed long delay.
template <class Predicate>
bool Await(Predicate predicate, std::chrono::milliseconds timeout = 2500ms)
{
    const auto end = std::chrono::steady_clock::now() + timeout;
    while (!predicate() && std::chrono::steady_clock::now() < end)
        std::this_thread::sleep_for(1ms);
    return predicate();
}

/** @brief An actual callback boundary held until the observer releases it. */
class Gate {
public:
    /// Announce callback entry and await an explicit bounded release.
    void Enter()
    {
        std::unique_lock<std::mutex> lock(mutex_);
        entered_ = true;
        changed_.notify_all();
        if (!changed_.wait_for(lock, 2500ms, [this] { return released_; }))
            throw std::runtime_error("navigation callback gate timed out");
    }
    /// Observe actual worker entry.
    bool WaitEntered()
    {
        std::unique_lock<std::mutex> lock(mutex_);
        return changed_.wait_for(lock, 2500ms, [this] { return entered_; });
    }
    /// Release before waiting for futures, including on failed observations.
    void Release()
    {
        std::lock_guard<std::mutex> lock(mutex_);
        released_ = true;
        changed_.notify_all();
    }
private:
    /// Protects callback handshake flags.
    std::mutex mutex_;
    /// Entry/release notification.
    std::condition_variable changed_;
    /// Callback has reached the boundary.
    bool entered_{false};
    /// Observer has released the callback.
    bool released_{false};
};

/** @brief Effects generated by real native nodes, retained across replacements. */
struct Probe {
    /// Actual node starts, including same-pose new identities.
    std::atomic<unsigned> starts{0};
    /// Actual continuing ticks.
    std::atomic<unsigned> ticks{0};
    /// Actual native halt callbacks.
    std::atomic<unsigned> halts{0};
    /// Enable a single preinstalled callback after acceptance has returned.
    std::atomic<bool> invoke{false};
    /// Exercise cleanup failure in the real runner.
    std::atomic<bool> fail_halt{false};
    /// Installed before starting; never replaced while the worker is active.
    std::function<void()> callback;
    /// Protect the last identity observed inside a real node.
    std::mutex mutex;
    /// Domain-populated invocation identity, independent of public metadata timing.
    std::string observed_task;
};

/** @brief Stateful node with production blackboard identity and observable effects. */
class NavigationProbe final : public BT::StatefulActionNode {
public:
    /// Resolve only fixture effects; invocation data comes from NavigationTask.
    NavigationProbe(const std::string& name, const BT::NodeConfig& config)
        : BT::StatefulActionNode(name, config),
          probe_(config.blackboard->get<std::shared_ptr<Probe>>("navigation_probe")) {}
    /// No XML ports; the host supplies typed blackboard evidence.
    static BT::PortsList providedPorts() { return {}; }
    /// Count an actual start and record the domain's committed invocation.
    BT::NodeStatus onStart() override
    {
        const auto id = config().blackboard->get<std::string>("navigation_task_id");
        { std::lock_guard<std::mutex> lock(probe_->mutex); probe_->observed_task = id; }
        ++probe_->starts;
        return BT::NodeStatus::RUNNING;
    }
    /// Exercise callback reentry on the real worker, at most once per fixture.
    BT::NodeStatus onRunning() override
    {
        ++probe_->ticks;
        if (probe_->invoke.exchange(false) && probe_->callback) probe_->callback();
        return BT::NodeStatus::RUNNING;
    }
    /// Count native cleanup and optionally expose its exception path.
    void onHalted() override
    {
        ++probe_->halts;
        if (probe_->fail_halt.load()) throw std::runtime_error("fixture halt failure");
    }
private:
    /// Effects outlive all replaced trees.
    std::shared_ptr<Probe> probe_;
};

/// Register through Autonomy's actual registry, preserving builtin nodes.
void RegisterProbe(BT::BehaviorTreeFactory& factory)
{
    factory.registerNodeType<NavigationProbe>("NavigationLifecycleProbe");
}

/** @brief Own a unique native XML file until all workers are joined. */
class XmlFile {
public:
    /// Write a builtin success or stateful production-factory tree.
    explicit XmlFile(bool immediate = false)
    {
        static std::atomic<unsigned> sequence{0};
        path_ = std::filesystem::temp_directory_path() /
            ("autonomy-navigation-" + std::to_string(
                std::chrono::steady_clock::now().time_since_epoch().count()) +
             "-" + std::to_string(++sequence) + ".xml");
        std::ofstream out(path_);
        out << "<root BTCPP_format=\"4\" main_tree_to_execute=\"Test\">"
               "<BehaviorTree ID=\"Test\">"
            << (immediate ? "<AlwaysSuccess/>" : "<NavigationLifecycleProbe/>")
            << "</BehaviorTree></root>";
        Require(static_cast<bool>(out), "write native navigation XML");
    }
    /// Remove only the fixture file.
    ~XmlFile() { std::error_code error; std::filesystem::remove(path_, error); }
    /// Return the native XML pathname.
    std::string path() const { return path_.string(); }
private:
    /// Unique file path, outliving its task fixture.
    std::filesystem::path path_;
};

/** @brief Control only remote dependencies while retaining actual domain behavior. */
class Harness final : public NavigationTask {
public:
    /// Join while derived dependency fixtures remain alive.
    ~Harness() override { fail_cancel.store(false); try { Shutdown(); } catch (...) {} }
    /// Real worker completion.
    bool done() { return !runner()->IsRunning(); }
    /// Actual next-tick eligibility for observing the preemption boundary.
    bool eligible() { return BeforeTreeTick(); }
    /// Identify the actual thread that reached its readiness probe.
    bool was_probed(std::thread::id id) const
    {
        std::lock_guard<std::mutex> lock(probed_mutex_);
        return probed_threads_.count(id) != 0;
    }
    /// RPC readiness, independently switchable from fixture node execution.
    std::atomic<bool> ready{true};
    /// Exercise an exception before replacement starts.
    std::atomic<bool> fail_probe{false};
    /// Exercise uncertain remote cancellation.
    std::atomic<bool> fail_cancel{false};
    /// Observe entry into actual readiness waiting.
    mutable std::atomic<unsigned> probes{0};
    /// Observe real domain requests to cancel its dependency.
    std::atomic<unsigned> cancels{0};
    /// Bounded production-policy seam; installed before any submission.
    std::chrono::milliseconds deadline{150ms};
    /// Owned native node effects.
    std::shared_ptr<Probe> probe = std::make_shared<Probe>();
protected:
    /// The fixture needs no network client; it tests actual domain admission.
    bool EnsureNavigationClient() override { return true; }
    /// Model remote availability without replacing readiness orchestration.
    bool NavigationServersReady() const override
    {
        { std::lock_guard<std::mutex> lock(probed_mutex_);
          probed_threads_.insert(std::this_thread::get_id()); }
        ++probes;
        if (fail_probe.load()) throw std::runtime_error("fixture readiness failure");
        return ready.load();
    }
    /// Keep fixture deadlines bounded; production remains twenty seconds.
    std::chrono::milliseconds NavigationReadyTimeout() const override { return deadline; }
    /// Observe the actual domain's remote cancellation boundary.
    void CancelRemoteNavigation() override
    {
        ++cancels;
        if (fail_cancel.load()) throw std::runtime_error("fixture cancellation failure");
    }
    /// Retain all production blackboard fields and add only node effect storage.
    void PopulateBlackboard(const BT::Blackboard::Ptr& board) override
    {
        NavigationTask::PopulateBlackboard(board);
        board->set("navigation_probe", probe);
    }
private:
    /// Protect identities of actual readiness callers.
    mutable std::mutex probed_mutex_;
    /// Readiness thread evidence, used for deterministic supersession ordering.
    mutable std::set<std::thread::id> probed_threads_;
};

/// Construct a valid actual protobuf goal with distinct public identity.
proto::NavigationGoal Goal(const XmlFile& xml, const std::string& id = "A")
{
    proto::NavigationGoal goal;
    goal.set_command(proto::NAV_CMD_START);
    goal.mutable_header()->set_task_id(id);
    goal.mutable_header()->set_client_id("exploration-parent");
    goal.mutable_plugins()->set_behavior_tree(xml.path());
    auto* pose = goal.add_goals();
    pose->mutable_header()->set_frame_id("map");
    pose->mutable_pose()->mutable_position()->set_x(2.0);
    pose->mutable_pose()->mutable_orientation()->set_w(1.0);
    return goal;
}

/// Initialize the actual factory and launch a real node.
void Start(Harness& task, const proto::NavigationGoal& goal)
{
    proto::TaskServerOptions options;
    Require(task.Initialize(options), "initialize actual NavigationTask");
    Require(task.SubmitGoal(goal), "accept valid native navigation goal");
    Require(Await([&] { return task.probe->starts.load() == 1; }), "native action starts");
}

/// Require metadata and lifecycle together, after SubmitGoal has returned.
void Identity(Harness& task, const std::string& id, TaskLifecycle state)
{
    Require(task.GetSnapshot().task_id() == id && task.GetLifecycle() == state,
            "accepted identity and actual lifecycle agree");
}

/// Same geometry with a new task identity must launch fresh node effects.
void SamePoseNewIdentity()
{
    XmlFile xml; Harness task; Start(task, Goal(xml));
    Require(task.SubmitGoal(Goal(xml, "B")), "same pose new identity accepted");
    Require(Await([&] { return task.probe->starts == 2; }), "new identity starts fresh tree");
    Identity(task, "B", TaskLifecycle::kRunning);
    std::lock_guard<std::mutex> lock(task.probe->mutex);
    Require(task.probe->observed_task == "B", "node uses new domain identity");
}

/// Exact named retries preserve the invocation; REPLAN always starts another.
void RetryAndReplan()
{
    XmlFile xml; Harness task; auto goal = Goal(xml); Start(task, goal);
    Require(task.SubmitGoal(goal) && task.probe->starts == 1, "exact retry is idempotent");
    goal.set_command(proto::NAV_CMD_REPLAN);
    Require(task.SubmitGoal(goal), "REPLAN accepted");
    Require(Await([&] { return task.probe->starts == 2; }), "REPLAN creates invocation");
    goal.set_command(proto::NAV_CMD_START);
    goal.mutable_plugins()->set_controller_id("changed-controller");
    Require(task.SubmitGoal(goal), "changed plugin goal accepted");
    Require(Await([&] { return task.probe->starts == 3; }), "plugin change restarts tree");
}

