/// Cancel only the waiting request, without canceling an unrelated active goal.
void TargetedPendingCancellation()
{
    XmlFile xml; Harness task; task.deadline=2000ms; Start(task, Goal(xml));
    task.ready.store(false); const auto probes=task.probes.load();
    auto pending=std::async(std::launch::async,[&]{return task.SubmitGoal(Goal(xml,"B"));});
    Require(Await([&]{return task.probes>probes;}), "pending waiter reached readiness");
    Require(!task.CancelForTask("wrong"), "wrong identity rejected");
    Require(task.CancelForTask("B"), "pending identity canceled");
    Require(pending.wait_for(500ms)==std::future_status::ready && !pending.get(),
            "cancellation interrupts long readiness wait");
    Identity(task,"A",TaskLifecycle::kRunning);
    Require(task.probe->halts==0, "pending cancel preserves accepted node");
}

/// A newer goal supersedes the older waiter, whose acceptance must return false.
void SupersededWaiter()
{
    XmlFile xml; Harness task; task.deadline=2000ms; Start(task,Goal(xml));
    task.ready.store(false); const auto probes=task.probes.load();
    auto older=std::async(std::launch::async,[&]{return task.SubmitGoal(Goal(xml,"B"));});
    Require(Await([&]{return task.probes>probes;}), "older goal waits");
    std::promise<std::thread::id> identity;
    auto identity_future=identity.get_future();
    auto newer=std::async(std::launch::async,[&]{
        identity.set_value(std::this_thread::get_id());
        return task.SubmitGoal(Goal(xml,"C"));
    });
    const auto newer_thread=identity_future.get();
    Require(Await([&]{return task.was_probed(newer_thread);}), "newer request reserves before readiness");
    task.ready.store(true);
    Require(newer.wait_for(500ms)==std::future_status::ready && newer.get(), "newer goal accepted");
    Require(older.wait_for(500ms)==std::future_status::ready && !older.get(),
            "older superseded waiter rejected");
    Identity(task,"C",TaskLifecycle::kRunning);
}

