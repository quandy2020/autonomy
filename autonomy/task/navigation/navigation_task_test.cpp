/// A newer replacement may supersede another while the old worker is being joined.
void SupersededDuringJoin()
{
    XmlFile xml; Gate gate; Harness task;
    task.probe->callback=[&]{gate.Enter();}; Start(task,Goal(xml));
    task.probe->invoke=true; Require(gate.WaitEntered(), "old worker reaches callback");
    auto older=std::async(std::launch::async,[&]{return task.SubmitGoal(Goal(xml,"B"));});
    const bool revoked=Await([&]{return !task.eligible();});
    const auto probes=task.probes.load();
    auto newer=std::async(std::launch::async,[&]{return task.SubmitGoal(Goal(xml,"C"));});
    const bool entered=Await([&]{return task.probes>probes;});
    gate.Release();
    Require(revoked && entered, "replacement boundary observed before release");
    Require(older.wait_for(500ms)==std::future_status::ready && !older.get(),
            "joined older request rejects supersession");
    Require(newer.wait_for(500ms)==std::future_status::ready && newer.get(),
            "newest request starts after preceding worker cleanup");
    Identity(task,"C",TaskLifecycle::kRunning);
    Require(Await([&]{return task.probe->starts==2;}), "only newest replacement executes");
}

