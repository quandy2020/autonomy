// Helper function to create planner options with navfn configuration
proto::PlannerOptions CreatePlannerOptions() {
    proto::PlannerOptions options;
    auto* navfn = options.mutable_navfn();
    navfn->set_tolerance(0.0);
    navfn->set_use_astar(false);
    navfn->set_allow_unknown(true);
    navfn->set_use_final_approach_orientation(false);
    return options;
}

// Helper function to create a pose
commsgs::geometry_msgs::PoseStamped CreatePose(
    double x, double y, const std::string& frame_id = "map") {
    commsgs::geometry_msgs::PoseStamped pose;
    pose.header.frame_id = frame_id;
    pose.pose.position.x = x;
    pose.pose.position.y = y;
    pose.pose.position.z = 0.0;
    pose.pose.orientation.w = 1.0;
    return pose;
}

// Test function: load map from PNG/PGM, plan path, save result to PNG
void TestPathPlanningFromImage(const std::string& input_image_path,
                               const std::string& output_image_path,
                               double start_x, double start_y, double goal_x,
                               double goal_y, double resolution = 0.05,
                               double origin_x = 0.0, double origin_y = 0.0) {
    // Step 1: Load map from PNG/PGM image (using loadFromPgm which supports PNG
    // via ImageMagick)
    AINFO << "Loading map from: " << input_image_path;
    utils::PgmConverter::LoadParameters load_params;
    load_params.resolution = resolution;
    load_params.origin_x = origin_x;
    load_params.origin_y = origin_y;
    load_params.origin_yaw = 0.0;

    auto costmap =
        utils::PgmConverter::loadFromPgm(input_image_path, load_params);

    if (!costmap) {
        AERROR << "Failed to load map from: " << input_image_path;
        GTEST_FAIL() << "Failed to load map from image file";
        return;
    }

    AINFO << "Map loaded: " << costmap->getSizeInCellsX() << "x"
          << costmap->getSizeInCellsY()
          << " cells, resolution: " << costmap->getResolution() << " m/pixel";

    // Step 3: Create start and goal poses
    auto start = CreatePose(start_x, start_y, "map");
    auto goal = CreatePose(goal_x, goal_y, "map");

    AINFO << "Planning path from (" << start_x << ", " << start_y << ") to ("
          << goal_x << ", " << goal_y << ")";

    // Step 4: For a complete test, you would:
    // 1. Initialize autolink: autolink::Init(argc, argv);
    // 2. Create node: auto node = autolink::CreateNode("test_node");
    // 3. Create costmap wrapper with the loaded costmap
    // 4. Configure planner: planner.Configure(options, "test_navfn", wrapper);
    // 5. Plan path: planner.CreatePlan(start, goal, plan, cancel_checker);

    // For this demonstration, we create a simple path to visualize
    // In a real scenario, this would be generated by the planner
    commsgs::planning_msgs::Path plan;
    plan.header.frame_id = "map";
    plan.poses.clear();

    // Create a demonstration path (straight line for visualization)
    // Note: Actual planner would generate an obstacle-avoiding path
    int num_points = 30;
    for (int i = 0; i < num_points; ++i) {
        double t = static_cast<double>(i) / (num_points - 1);
        auto pose = CreatePose(start_x + (goal_x - start_x) * t,
                               start_y + (goal_y - start_y) * t, "map");
        plan.poses.push_back(pose);
    }

    // Step 5: Save path to image

    utils::PgmConverter::RenderParameters render_params;
    render_params.draw_start_marker = true;
    render_params.draw_goal_marker = true;
    render_params.draw_path_points =
        false;  // Set to true to show individual path points
    render_params.path_line_width = 3.0;
    render_params.start_marker_size = 10.0;
    render_params.goal_marker_size = 10.0;

    bool saved = utils::PgmConverter::savePathToImage(
        *costmap, plan, output_image_path, render_params);

    EXPECT_TRUE(saved) << "Failed to save path to image file: "
                       << output_image_path;

    if (saved) {
        AINFO << "Path planning result saved to: " << output_image_path;
        // Verify file was created
        std::ifstream file(output_image_path);
        EXPECT_TRUE(file.good())
            << "Output image file does not exist: " << output_image_path;
        file.close();
    }
}

// Test case: Path planning from PNG image using default turtlebot3_house map
TEST(NavfnPlannerImageTest, PlanPathFromPngImage) {
    // Use default turtlebot3_house.pgm map
    using namespace autonomy::map::utils;
    const std::string input_image =
        GetMapDataFilesDirectory() + "turtlebot3_house.pgm";
    const std::string output_image = "/tmp/navfn_path_result.png";
    const double resolution = 0.05;  // From turtlebot3_house.yaml
    const double origin_x = -5.71;   // From turtlebot3_house.yaml
    const double origin_y = -4.96;   // From turtlebot3_house.yaml

    // Check if map file exists
    std::ifstream map_file(input_image);
    if (!map_file.good()) {
        GTEST_SKIP() << "Default map file not found: " << input_image
                     << ", skipping test";
        return;
    }
    map_file.close();

    // Test path planning with default map
    // Start and goal positions adjusted for the map's origin
    // Start near the origin, goal at a reasonable position in the map
    TestPathPlanningFromImage(
        input_image, output_image, -5.0,
        -4.0,      // start position (in meters, adjusted for origin)
        0.0, 0.0,  // goal position (in meters, adjusted for origin)
        resolution,
        origin_x,   // map origin x
        origin_y);  // map origin y

    // Note: output_image is kept for manual inspection
}

// Test case: Path planning with custom image path (when provided) or default
// map Usage: Set TEST_MAP_IMAGE environment variable to path of your PNG/PGM
// map file If not set, uses default turtlebot3_house.pgm
TEST(NavfnPlannerImageTest, PlanPathFromCustomImage) {
    using namespace autonomy::map::utils;

    // Use custom map from environment variable if provided, otherwise use
    // default
    const char* custom_map = std::getenv("TEST_MAP_IMAGE");
    std::string input_image;
    double resolution = 0.05;
    double origin_x = 0.0;
    double origin_y = 0.0;

    if (custom_map) {
        input_image = custom_map;
        AINFO << "Using custom map from environment: " << input_image;
    } else {
        // Use default turtlebot3_house.pgm
        input_image = GetMapDataFilesDirectory() + "turtlebot3_house.pgm";
        resolution = 0.05;  // From turtlebot3_house.yaml
        origin_x = -5.71;   // From turtlebot3_house.yaml
        origin_y = -4.96;   // From turtlebot3_house.yaml
        AINFO << "Using default map: " << input_image;
    }

    const std::string output_image = "/tmp/navfn_custom_result.png";

    // Load map to get its dimensions
    utils::PgmConverter::LoadParameters load_params;
    load_params.resolution = resolution;
    load_params.origin_x = origin_x;
    load_params.origin_y = origin_y;
    load_params.origin_yaw = 0.0;
    auto costmap = utils::PgmConverter::loadFromPgm(input_image, load_params);

    if (!costmap) {
        GTEST_FAIL() << "Failed to load map image from: " << input_image;
        return;
    }

    // Calculate start and goal positions relative to map origin
    // For default map, use reasonable positions adjusted for origin
    double start_x, start_y, goal_x, goal_y;
    if (custom_map) {
        // For custom maps, use percentage of map size
        double map_width =
            costmap->getSizeInCellsX() * costmap->getResolution();
        double map_height =
            costmap->getSizeInCellsY() * costmap->getResolution();
        start_x = origin_x + map_width * 0.1;
        start_y = origin_y + map_height * 0.1;
        goal_x = origin_x + map_width * 0.9;
        goal_y = origin_y + map_height * 0.9;
    } else {
        // For default turtlebot3_house map, use fixed positions
        start_x = -5.0;
        start_y = -4.0;
        goal_x = 0.0;
        goal_y = 0.0;
    }

    AINFO << "Map size: "
          << costmap->getSizeInCellsX() * costmap->getResolution() << "m x "
          << costmap->getSizeInCellsY() * costmap->getResolution() << "m";
    AINFO << "Planning from (" << start_x << ", " << start_y << ") to ("
          << goal_x << ", " << goal_y << ")";

    TestPathPlanningFromImage(input_image, output_image, start_x, start_y,
                              goal_x, goal_y, costmap->getResolution(),
                              origin_x, origin_y);

    AINFO << "Test completed. Result saved to: " << output_image;
}

