/**
 * @file rpc_teleop_handlers.hpp
 * @brief TeleopService RpcHandlers: Velocity (bidi), Drive/BackUp/Spin streams,
 *        Cancel/Pause/Resume, GetStatus.
 *
 * @details
 * Forwards to Context::teleop() (TeleopStub). Velocity uses GoalChannel topics
 * @c kTeleopGoal / @c kTeleopFeedback (`/autonomy/task/teleop/{goal,feedback}`);
 * relative Drive/BackUp/Spin use Action servers (@c kDriveOnHeadingActionName,
 * @c kBackUpActionName, @c kSpinActionName) via TeleopRelativeBackend.
 *
 * Types:
 * - RpcTeleopVelocityHandler — hand-rolled bidi class (SMART_PTR)
 * - RpcTeleopDriveOnHeadingHandler / RpcTeleopBackUpHandler / RpcTeleopSpinHandler — BRIDGE_STREAM
 * - RpcTeleopCancelHandler / RpcTeleopPauseHandler / RpcTeleopResumeHandler —
 *   BRIDGE_DECL + inline
 * - RpcTeleopGetStatusHandler — BRIDGE_GET GetSnapshot
 *
 * Invariants:
 * - Velocity is hand-rolled (session + OnReadsDone); other streams use
 *   StreamHandler + IsTeleopResponseTerminal.
 * - Cancel/Pause/Resume are BRIDGE_DECL with inline OnRequest (Pause/Resume
 *   validate stub return bool).
 * - Ownership: per-RPC handlers; TeleopStub owned by Context / CancelRegistry.
 * - Threading: gRPC CQ; relative actions run on WorkScheduler.
 *
 * @see TeleopStub
 * @see handler_templates.hpp
 */

