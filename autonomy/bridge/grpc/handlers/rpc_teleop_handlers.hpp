/**
 * @brief Cancel OnRequest: CancelGoal(goal_id) then OkStatus(kCancelled).
 *
 * @param[in] request GoalRequest with optional goal_id filter.
 */
inline void RpcTeleopCancelHandler::OnRequest(
    const ::automsgs::rpcs::teleop::GoalRequest& request) {
    ReplyStatusWithContext(this, [&](auto* context) {
        context->teleop().CancelGoal(request.goal_id());
        return OkStatus(kCancelled);
    });
}

/**
 * @brief Pause OnRequest: PauseGoal or INVALID_ARGUMENT("nothing to pause").
 *
 * @param[in] request GoalRequest with optional goal_id filter.
 */
inline void RpcTeleopPauseHandler::OnRequest(
    const ::automsgs::rpcs::teleop::GoalRequest& request) {
    ReplyStatusWithContext(this, [&](auto* context) {
        return context->teleop().PauseGoal(request.goal_id())
                   ? OkStatus(kPaused)
                   : ErrorStatus(
                         ::automsgs::msgs::status_msgs::INVALID_ARGUMENT,
                         "nothing to pause");
    });
}

/**
 * @brief Resume OnRequest: ResumeGoal or INVALID_ARGUMENT("nothing to resume").
 *
 * @param[in] request GoalRequest with optional goal_id filter.
 */
inline void RpcTeleopResumeHandler::OnRequest(
    const ::automsgs::rpcs::teleop::GoalRequest& request) {
    ReplyStatusWithContext(this, [&](auto* context) {
        return context->teleop().ResumeGoal(request.goal_id())
                   ? OkStatus(kResumed)
                   : ErrorStatus(
                         ::automsgs::msgs::status_msgs::INVALID_ARGUMENT,
                         "nothing to resume");
    });
}

