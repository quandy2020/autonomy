#!/usr/bin/env bash
# Download, build, and install HesaiLidar_SDK_2.0 for local development.
# Upstream: https://github.com/HesaiTechnology/HesaiLidar_SDK_2.0
#
# Note: autodriver's XT32 UDP path (backend: hesai) is self-contained and does
# not link this SDK. Install it when you need the official parser / PTC tools /
# multi-model support from Hesai.
#
# Usage:
#   ./scripts/install_hesai_lidar_sdk.sh
#   PREFIX=/usr/local ./scripts/install_hesai_lidar_sdk.sh
#   ./scripts/install_hesai_lidar_sdk.sh /path/to/HesaiLidar_SDK_2.0
#
# Env:
#   PREFIX                 install prefix (default: /usr/local)
#   HESAI_SDK_SRC          existing checkout (skip clone)
#   HESAI_SDK_REPO         git URL
#   HESAI_SDK_REF          git ref (default: master)
#   HESAI_SDK_DIR          clone/cache directory (default: /tmp/HesaiLidar_SDK_2.0-src)
#   HESAI_WITH_PTCS        1 = enable OpenSSL PTCS (default: 0)
#   HESAI_BUILD_SAMPLES    1 = build sample / multi_test (default: 0)
#   HESAI_INSTALL_APT_DEPS 1 = apt-get install build deps (default: 1)
#   HESAI_FORCE            1 = reinstall even if already present

set -euo pipefail

REPO_URL="${HESAI_SDK_REPO:-https://github.com/HesaiTechnology/HesaiLidar_SDK_2.0.git}"
REF="${HESAI_SDK_REF:-master}"
PREFIX="${PREFIX:-/usr/local}"
CACHE_DIR="${HESAI_SDK_DIR:-/tmp/HesaiLidar_SDK_2.0-src}"
WITH_PTCS="${HESAI_WITH_PTCS:-0}"
BUILD_SAMPLES="${HESAI_BUILD_SAMPLES:-0}"
INSTALL_APT_DEPS="${HESAI_INSTALL_APT_DEPS:-1}"

ROOT_NAME="hesai_lidar_sdk"
INSTALL_ROOT="${PREFIX}/opt/${ROOT_NAME}"

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "missing required command: $1" >&2
    exit 1
  }
}

run_priv() {
  if [[ -w "${PREFIX}" ]] || [[ "$(id -u)" -eq 0 ]]; then
    "$@"
  else
    need_cmd sudo
    sudo "$@"
  fi
}

sdk_already_installed() {
  if [[ "${HESAI_FORCE:-0}" == "1" ]]; then
    return 1
  fi
  [[ -f "${INSTALL_ROOT}/driver/hesai_lidar_sdk.hpp" ]] \
    && [[ -f "${INSTALL_ROOT}/lib/libsource_lib.a" ]]
}

install_apt_deps() {
  if [[ "${INSTALL_APT_DEPS}" != "1" ]]; then
    return 0
  fi
  if ! command -v apt-get >/dev/null 2>&1; then
    echo "apt-get not found; skip system deps (install cmake/g++/libpcap yourself)" >&2
    return 0
  fi
  local pkgs=(build-essential cmake git libpcap-dev)
  if [[ "${WITH_PTCS}" == "1" ]]; then
    pkgs+=(libssl-dev)
  fi
  # Upstream README also lists libpcl-dev / libyaml-cpp-dev for optional tools;
  # root CMake does not require them for the core libraries.
  echo "== apt install: ${pkgs[*]} =="
  run_priv apt-get update -qq
  run_priv apt-get install -y --no-install-recommends "${pkgs[@]}"
}

download_sdk() {
  need_cmd git
  if [[ -f "${CACHE_DIR}/driver/hesai_lidar_sdk.hpp" && -d "${CACHE_DIR}/.git" ]]; then
    echo "== Updating ${CACHE_DIR} (${REF}) =="
    git -C "${CACHE_DIR}" fetch --depth 1 origin "${REF}"
    git -C "${CACHE_DIR}" checkout -q FETCH_HEAD || \
      git -C "${CACHE_DIR}" checkout -q "${REF}"
    git -C "${CACHE_DIR}" submodule update --init --recursive --depth 1 || \
      git -C "${CACHE_DIR}" submodule update --init --recursive
  else
    echo "== Cloning ${REPO_URL} (${REF}) -> ${CACHE_DIR} =="
    rm -rf "${CACHE_DIR}"
    # ZIP downloads break symlinks; always use git + submodules.
    if ! git clone --depth 1 --recurse-submodules --branch "${REF}" \
      "${REPO_URL}" "${CACHE_DIR}"; then
      git clone --depth 1 --recurse-submodules "${REPO_URL}" "${CACHE_DIR}"
      git -C "${CACHE_DIR}" checkout -q "${REF}" || true
      git -C "${CACHE_DIR}" submodule update --init --recursive
    fi
  fi
  echo "${CACHE_DIR}"
}

resolve_src() {
  if [[ $# -ge 1 && -n "${1}" ]]; then
    echo "${1}"
    return
  fi
  if [[ -n "${HESAI_SDK_SRC:-}" ]]; then
    echo "${HESAI_SDK_SRC}"
    return
  fi
  download_sdk
}

write_cmake_config() {
  local cfg_dir="${PREFIX}/lib/cmake/HesaiLidarSDK"
  local cfg="${cfg_dir}/HesaiLidarSDKConfig.cmake"
  run_priv mkdir -p "${cfg_dir}"
  run_priv tee "${cfg}" >/dev/null <<EOF
# Generated by autodriver scripts/install_hesai_lidar_sdk.sh
# Upstream: https://github.com/HesaiTechnology/HesaiLidar_SDK_2.0

set(HesaiLidarSDK_FOUND TRUE)
set(HesaiLidarSDK_VERSION "2.0")
set(HesaiLidarSDK_ROOT "${INSTALL_ROOT}")

# Mirrors upstream hesai_sdk_lib / lidar_lib / udpParser_lib INTERFACE includes.
set(HesaiLidarSDK_INCLUDE_DIRS
  "\${HesaiLidarSDK_ROOT}"
  "\${HesaiLidarSDK_ROOT}/driver"
  "\${HesaiLidarSDK_ROOT}/generated"
  "\${HesaiLidarSDK_ROOT}/libhesai"
  "\${HesaiLidarSDK_ROOT}/libhesai/Lidar"
  "\${HesaiLidarSDK_ROOT}/libhesai/Common"
  "\${HesaiLidarSDK_ROOT}/libhesai/Common/include"
  "\${HesaiLidarSDK_ROOT}/libhesai/Logger/include"
  "\${HesaiLidarSDK_ROOT}/libhesai/Source/include"
  "\${HesaiLidarSDK_ROOT}/libhesai/PtcClient/include"
  "\${HesaiLidarSDK_ROOT}/libhesai/PtcParser"
  "\${HesaiLidarSDK_ROOT}/libhesai/PtcParser/include"
  "\${HesaiLidarSDK_ROOT}/libhesai/SerialClient/include"
  "\${HesaiLidarSDK_ROOT}/libhesai/UdpParser"
  "\${HesaiLidarSDK_ROOT}/libhesai/UdpParser/include"
  "\${HesaiLidarSDK_ROOT}/libhesai/UdpProtocol"
  "\${HesaiLidarSDK_ROOT}/libhesai/Container/include"
  "\${HesaiLidarSDK_ROOT}/libhesai/Container/src"
)

find_library(HesaiLidarSDK_PCAP_LIBRARY NAMES pcap)
set(HesaiLidarSDK_LIBRARIES
  "\${HesaiLidarSDK_ROOT}/lib/libserialClient_lib.a"
  "\${HesaiLidarSDK_ROOT}/lib/libptcClient_lib.a"
  "\${HesaiLidarSDK_ROOT}/lib/libsource_lib.a"
  "\${HesaiLidarSDK_ROOT}/lib/libplatutils_lib.a"
  "\${HesaiLidarSDK_ROOT}/lib/liblog_lib.a"
  Threads::Threads
)
if(HesaiLidarSDK_PCAP_LIBRARY)
  list(APPEND HesaiLidarSDK_LIBRARIES "\${HesaiLidarSDK_PCAP_LIBRARY}")
endif()

include(CMakeFindDependencyMacro)
find_dependency(Threads)

if(NOT TARGET HesaiLidarSDK::hesai_sdk)
  add_library(HesaiLidarSDK::hesai_sdk INTERFACE IMPORTED)
  set_target_properties(HesaiLidarSDK::hesai_sdk PROPERTIES
    INTERFACE_INCLUDE_DIRECTORIES "\${HesaiLidarSDK_INCLUDE_DIRS}"
    INTERFACE_LINK_LIBRARIES "\${HesaiLidarSDK_LIBRARIES}"
  )
endif()
EOF
}

install_tree() {
  local src="$1"
  local build="$2"

  echo "== Installing to ${INSTALL_ROOT} (PREFIX=${PREFIX}) =="
  run_priv rm -rf "${INSTALL_ROOT}"
  run_priv mkdir -p "${INSTALL_ROOT}/lib" "${INSTALL_ROOT}/generated"

  # Preserve source layout (SDK has no cmake --install; headers are relative).
  if command -v rsync >/dev/null 2>&1; then
    run_priv rsync -a \
      --exclude '.git/' \
      --exclude 'build/' \
      --exclude 'tool/build/' \
      "${src}/" "${INSTALL_ROOT}/"
  else
    run_priv mkdir -p "${INSTALL_ROOT}"
    run_priv cp -a "${src}/." "${INSTALL_ROOT}/"
    run_priv rm -rf "${INSTALL_ROOT}/.git" "${INSTALL_ROOT}/build"
  fi

  run_priv install -m 644 "${build}/generated/sdk_version.hpp" \
    "${INSTALL_ROOT}/generated/sdk_version.hpp"
  # Convenient copy next to the public header (matches #include "sdk_version.hpp").
  run_priv install -m 644 "${build}/generated/sdk_version.hpp" \
    "${INSTALL_ROOT}/driver/sdk_version.hpp"

  local lib
  for lib in \
    liblog_lib.a \
    libplatutils_lib.a \
    libsource_lib.a \
    libptcClient_lib.a \
    libserialClient_lib.a; do
    local found
    found="$(find "${build}" -name "${lib}" -type f | head -1 || true)"
    if [[ -z "${found}" ]]; then
      echo "missing build artifact: ${lib}" >&2
      exit 1
    fi
    run_priv install -m 644 "${found}" "${INSTALL_ROOT}/lib/${lib}"
    # Also expose under PREFIX/lib for simple -L/-l discovery.
    run_priv mkdir -p "${PREFIX}/lib"
    run_priv install -m 644 "${found}" "${PREFIX}/lib/${lib}"
  done

  write_cmake_config
}

# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

if sdk_already_installed; then
  echo "HesaiLidar_SDK already present at ${INSTALL_ROOT} (set HESAI_FORCE=1 to reinstall)"
  exit 0
fi

need_cmd cmake
need_cmd g++
need_cmd make

install_apt_deps

SRC="$(resolve_src "${1:-}")"
if [[ ! -f "${SRC}/driver/hesai_lidar_sdk.hpp" ]]; then
  echo "HesaiLidar_SDK_2.0 source invalid: ${SRC}" >&2
  echo "Expected driver/hesai_lidar_sdk.hpp (see ${REPO_URL})" >&2
  exit 1
fi
if [[ ! -f "${SRC}/libhesai/CMakeLists.txt" ]]; then
  echo "libhesai missing under ${SRC}; re-clone with --recurse-submodules" >&2
  exit 1
fi

BUILD_DIR="${SRC}/build-autodriver"
echo "== Configuring HesaiLidar_SDK_2.0 in ${BUILD_DIR} =="

CMAKE_ARGS=(
  -S "${SRC}"
  -B "${BUILD_DIR}"
  -DCMAKE_BUILD_TYPE=Release
  -DCMAKE_POSITION_INDEPENDENT_CODE=ON
)

if [[ "${WITH_PTCS}" == "1" ]]; then
  CMAKE_ARGS+=(-DWITH_PTCS_USE=ON)
else
  CMAKE_ARGS+=(-DWITH_PTCS_USE=OFF)
fi

if [[ "${BUILD_SAMPLES}" == "1" ]]; then
  CMAKE_ARGS+=(-DDISENABLE_TEST_CC=OFF)
else
  CMAKE_ARGS+=(-DDISENABLE_TEST_CC=ON)
fi

cmake "${CMAKE_ARGS[@]}"
cmake --build "${BUILD_DIR}" -j"$(nproc)"

install_tree "${SRC}" "${BUILD_DIR}"

echo
echo "Installed HesaiLidar_SDK_2.0:"
echo "  tree : ${INSTALL_ROOT}"
echo "  libs : ${INSTALL_ROOT}/lib/*.a  (also copied to ${PREFIX}/lib)"
echo "  cmake: ${PREFIX}/lib/cmake/HesaiLidarSDK/HesaiLidarSDKConfig.cmake"
echo
echo "CMake consumer tip:"
echo "  list(APPEND CMAKE_PREFIX_PATH \"${PREFIX}\")"
echo "  find_package(HesaiLidarSDK REQUIRED)"
echo "  target_link_libraries(foo PRIVATE HesaiLidarSDK::hesai_sdk)"
echo
echo "autodriver:"
echo "  XT32 UDP path (default) does not need this SDK."
echo "  ROS_2.0-compatible SDK path: rebuild with -DAUTODRIVER_WITH_HESAI_SDK=ON"
echo "  and set use_sdk: true (see config/lidar/hesai/sdk.yaml)."
